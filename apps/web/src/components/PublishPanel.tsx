import { useEffect, useState } from 'react';
import { Link as RouterLink } from 'react-router-dom';
import Alert from '@mui/material/Alert';
import Box from '@mui/material/Box';
import Button from '@mui/material/Button';
import Chip from '@mui/material/Chip';
import Divider from '@mui/material/Divider';
import Link from '@mui/material/Link';
import Stack from '@mui/material/Stack';
import TextField from '@mui/material/TextField';
import Typography from '@mui/material/Typography';
import AutoAwesome from '@mui/icons-material/AutoAwesome';
import CloudUpload from '@mui/icons-material/CloudUpload';
import OpenInNew from '@mui/icons-material/OpenInNew';
import Save from '@mui/icons-material/Save';
import type { GeneratedClipDTO } from '@shorts/shared-types';
import { describeError } from '../api/client';
import { useApproveClip, useRegenerateMetadata, useRejectClip, useSettings, useUpdateClipMetadata } from '../api/hooks';
import { formatDateTime } from '../lib/format';
import { StatusChip } from './StatusChip';

const tagsToText = (tags: string[]) => tags.join(', ');
const textToTags = (t: string) => t.split(',').map((x) => x.trim()).filter(Boolean);

/** Title/description/tags editor plus approve → upload controls for one rendered Short. */
export function PublishPanel({ clip, canEdit }: { clip: GeneratedClipDTO; canEdit: boolean }) {
  const settings = useSettings();
  const save = useUpdateClipMetadata();
  const regen = useRegenerateMetadata();
  const approve = useApproveClip();
  const reject = useRejectClip();
  const [draft, setDraft] = useState({ title: clip.title, description: clip.description, tags: tagsToText(clip.tags) });

  // Refresh the form when the server copy changes (e.g. metadata generated by the worker).
  useEffect(() => {
    setDraft({ title: clip.title, description: clip.description, tags: tagsToText(clip.tags) });
  }, [clip.id, clip.title, clip.description, clip.tags]);

  const locked = clip.uploadStatus === 'QUEUED' || clip.uploadStatus === 'UPLOADING' || clip.uploadStatus === 'PUBLISHED';
  const dirty = draft.title !== clip.title || draft.description !== clip.description || draft.tags !== tagsToText(clip.tags);
  const titleTooLong = draft.title.length > 100;
  const yt = settings.data?.youtube;
  const mockUploads = yt?.uploadMode === 'mock';
  const notConnected = yt && !mockUploads && !yt.connected;
  const privacy = settings.data?.publishing.privacyStatus;
  const error = [save, regen, approve, reject].find((m) => m.isError)?.error;

  return (
    <Box sx={{ mt: 2 }}>
      <Divider sx={{ mb: 1.5 }} />
      <Stack direction="row" spacing={1} sx={{ alignItems: 'center', mb: 1, flexWrap: 'wrap', rowGap: 1 }}>
        <Typography variant="overline" color="text.secondary" sx={{ flexGrow: 1 }}>
          Publish to YouTube
        </Typography>
        <StatusChip status={clip.approvalStatus} />
        <StatusChip status={clip.uploadStatus} />
      </Stack>

      {clip.uploadStatus === 'PUBLISHED' && clip.youtubeUrl && (
        <Alert severity="success" sx={{ mb: 1.5 }} action={<Button size="small" href={clip.youtubeUrl} target="_blank" rel="noopener noreferrer" endIcon={<OpenInNew />}>Open</Button>}>
          {mockUploads || clip.youtubeVideoId?.startsWith('mock') ? 'Published (simulated upload — no real video was created).' : `Published ${formatDateTime(clip.publishedAt)}${privacy ? ` as ${privacy}` : ''}.`}
        </Alert>
      )}
      {clip.uploadStatus === 'QUEUED' && (
        <Alert severity="info" sx={{ mb: 1.5 }}>
          {clip.scheduledPublishAt ? `Queued. Uploads at ${formatDateTime(clip.scheduledPublishAt)} (daily limit / spacing in Settings → Publishing).` : 'Queued for upload…'}
          {clip.lastError && <Typography variant="caption" component="p">{clip.lastError}</Typography>}
        </Alert>
      )}
      {clip.uploadStatus === 'UPLOADING' && <Alert severity="info" sx={{ mb: 1.5 }}>Uploading to YouTube…</Alert>}
      {clip.uploadStatus === 'UPLOAD_FAILED' && (
        <Alert severity="error" sx={{ mb: 1.5 }}>
          Upload failed: {clip.lastError ?? 'unknown error'}
        </Alert>
      )}
      {clip.uploadStatus === 'NOT_UPLOADED' && clip.lastError && (
        <Alert severity="warning" sx={{ mb: 1.5 }}>
          {clip.lastError}
        </Alert>
      )}
      {!clip.title && !clip.lastError && (
        <Typography variant="body2" color="text.secondary" sx={{ mb: 1 }}>
          Writing title and description…
        </Typography>
      )}

      <Stack spacing={1.5}>
        <TextField
          size="small"
          label="Title"
          value={draft.title}
          disabled={!canEdit || locked}
          onChange={(e) => setDraft((d) => ({ ...d, title: e.target.value }))}
          error={titleTooLong}
          helperText={`${draft.title.length}/100`}
        />
        <TextField
          size="small"
          label="Description"
          value={draft.description}
          disabled={!canEdit || locked}
          multiline
          minRows={3}
          maxRows={10}
          onChange={(e) => setDraft((d) => ({ ...d, description: e.target.value }))}
        />
        <TextField
          size="small"
          label="Tags"
          value={draft.tags}
          disabled={!canEdit || locked}
          helperText="Comma-separated"
          onChange={(e) => setDraft((d) => ({ ...d, tags: e.target.value }))}
        />
      </Stack>

      {canEdit && !locked && (
        <Stack direction="row" spacing={1} sx={{ mt: 1.5, flexWrap: 'wrap', rowGap: 1 }}>
          <Button
            size="small"
            variant="outlined"
            startIcon={<Save />}
            disabled={!dirty || titleTooLong || save.isPending}
            onClick={() => save.mutate({ id: clip.id, input: { title: draft.title, description: draft.description, tags: textToTags(draft.tags) } })}
          >
            Save
          </Button>
          <Button size="small" startIcon={<AutoAwesome />} disabled={regen.isPending} onClick={() => regen.mutate(clip.id)}>
            {regen.isPending ? 'Writing…' : 'Rewrite with AI'}
          </Button>
          <Box sx={{ flexGrow: 1 }} />
          {clip.approvalStatus !== 'REJECTED' && (
            <Button size="small" color="inherit" disabled={reject.isPending} onClick={() => reject.mutate(clip.id)}>
              Reject
            </Button>
          )}
          <Button
            size="small"
            variant="contained"
            startIcon={<CloudUpload />}
            disabled={dirty || !clip.title || approve.isPending || Boolean(notConnected)}
            onClick={() => approve.mutate(clip.id)}
          >
            {clip.uploadStatus === 'UPLOAD_FAILED' ? 'Retry upload' : 'Approve & upload'}
          </Button>
        </Stack>
      )}
      {canEdit && dirty && !locked && (
        <Typography variant="caption" color="text.secondary" component="p" sx={{ mt: 0.5 }}>
          Save your changes before approving.
        </Typography>
      )}
      {notConnected && (
        <Alert severity="warning" sx={{ mt: 1.5 }}>
          Connect the central YouTube channel in{' '}
          <Link component={RouterLink} to="/settings">
            Settings
          </Link>{' '}
          before uploading.
        </Alert>
      )}
      {mockUploads && !locked && (
        <Chip size="small" variant="outlined" label="Uploads are simulated until a YouTube OAuth client is configured" sx={{ mt: 1.5, maxWidth: '100%' }} />
      )}
      {error && (
        <Alert severity="error" sx={{ mt: 1.5 }}>
          {describeError(error)}
        </Alert>
      )}
    </Box>
  );
}
